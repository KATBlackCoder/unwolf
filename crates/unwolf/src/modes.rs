//! Decryption modes: the built-in table of UberWolf plus modes loaded from
//! `UberWolfConfig.json`.

use crate::dxa::DxaFormat;

/// One way of opening archives: a DX reader, a crypt version and a key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CryptMode {
    pub name: String,
    /// Crypt version stored in DXA v8 headers; 0 when the header has none.
    pub crypt_version: u16,
    pub format: DxaFormat,
    /// Key bytes exactly as UberWolf stores them, NUL terminators included.
    pub key: Vec<u8>,
}

impl CryptMode {
    fn bytes(name: &str, cv: u16, format: DxaFormat, key: &[u8]) -> Self {
        Self {
            name: name.into(),
            crypt_version: cv,
            format,
            key: key.to_vec(),
        }
    }

    /// A text key: UberWolf appends a NUL terminator.
    fn text(name: &str, cv: u16, format: DxaFormat, key: &str) -> Self {
        let mut k = key.as_bytes().to_vec();
        k.push(0);
        Self::bytes(name, cv, format, &k)
    }
}

