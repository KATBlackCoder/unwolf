mod tests {
    use super::*;

    #[test]
    fn eleven_modes_in_original_order() {
        let m = default_modes();
        assert_eq!(m.len(), 11);
        assert_eq!(m[3].name, "Wolf RPG v2.225");
        assert_eq!(m[7].crypt_version, 0x15E);
        assert_eq!(m[10].name, "One Way Heroics Plus");
    }
}
